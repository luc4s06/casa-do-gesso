-- Casa do Gesso — esquema do banco (Supabase / PostgreSQL)
-- Cole este arquivo inteiro em: Supabase > SQL Editor > New query > Run.
-- Pode ser executado mais de uma vez sem problema.

-- ---------------------------------------------------------------
-- Tabelas
-- ---------------------------------------------------------------
-- Os ids são texto (e não uuid) para poder importar os dados antigos do navegador
-- mantendo os mesmos ids e as referências entre clientes, retiradas e pagamentos.

create table if not exists public.clients (
  id          text primary key default gen_random_uuid()::text,
  name        text not null,
  phone       text not null,
  address     text,
  created_at  timestamptz not null default now()
);

create table if not exists public.withdrawals (
  id             text primary key default gen_random_uuid()::text,
  number         bigint generated by default as identity,
  client_id      text not null references public.clients (id) on delete restrict,
  date           timestamptz not null default now(),
  items          jsonb not null,
  subtotal       numeric(12, 2) not null,
  balance_before numeric(12, 2) not null,
  balance_after  numeric(12, 2) not null
);

create table if not exists public.payments (
  id             text primary key default gen_random_uuid()::text,
  number         bigint generated by default as identity,
  client_id      text not null references public.clients (id) on delete restrict,
  date           timestamptz not null default now(),
  amount         numeric(12, 2) not null check (amount > 0),
  method         text not null check (method in ('pix', 'dinheiro', 'cartao', 'outro')),
  note           text,
  balance_before numeric(12, 2) not null,
  balance_after  numeric(12, 2) not null
);

create table if not exists public.material_prices (
  material_id text primary key,
  price       numeric(12, 2) not null check (price >= 0),
  updated_at  timestamptz not null default now()
);

-- Uma única linha (id = 1) com os dados da empresa.
create table if not exists public.settings (
  id      integer primary key default 1 check (id = 1),
  name    text not null default 'Casa do Gesso',
  phone   text not null default '',
  address text not null default '',
  logo    text
);

create index if not exists withdrawals_client_idx on public.withdrawals (client_id);
create index if not exists withdrawals_date_idx   on public.withdrawals (date desc);
create index if not exists payments_client_idx    on public.payments (client_id);
create index if not exists payments_date_idx      on public.payments (date desc);

-- ---------------------------------------------------------------
-- Segurança (RLS): só quem está logado lê ou grava.
-- ---------------------------------------------------------------
alter table public.clients         enable row level security;
alter table public.withdrawals     enable row level security;
alter table public.payments        enable row level security;
alter table public.material_prices enable row level security;
alter table public.settings        enable row level security;

do $$
declare t text;
begin
  foreach t in array array['clients', 'withdrawals', 'payments', 'material_prices', 'settings']
  loop
    execute format('drop policy if exists "authenticated full access" on public.%I', t);
    execute format(
      'create policy "authenticated full access" on public.%I
         for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- ---------------------------------------------------------------
-- Usada pela importação dos dados antigos: depois de inserir registros com
-- número próprio, avança a contagem para o próximo número não colidir.
-- ---------------------------------------------------------------
create or replace function public.sync_number_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform setval(pg_get_serial_sequence('public.withdrawals', 'number'),
                 greatest((select coalesce(max(number), 0) from public.withdrawals), 1),
                 (select count(*) > 0 from public.withdrawals));
  perform setval(pg_get_serial_sequence('public.payments', 'number'),
                 greatest((select coalesce(max(number), 0) from public.payments), 1),
                 (select count(*) > 0 from public.payments));
end;
$$;

revoke all on function public.sync_number_sequences() from public, anon;
grant execute on function public.sync_number_sequences() to authenticated;
